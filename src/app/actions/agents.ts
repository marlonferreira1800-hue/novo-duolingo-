'use server';

import { createAiRuntime } from '@/ai/runtime';
import { cardiovascularEvidence } from '@/ai/evidence/cardiovascular';
import { evidenceKey } from '@/contracts/ai';
import { orchestratorRequestSchema, type AgentRunRecord, type OrchestratorDraft } from '@/contracts/ai';
import { AiRunError } from '@/ai/errors';

const sourceKey = evidenceKey(cardiovascularEvidence);

// Fixture padrão para o modo offline (sem AI_API_KEY): simula a cadeia de agentes
// retornando um rascunho demonstrativo. Nunca vira live silenciosamente.
function defaultFixtureResponses(locale: 'pt-BR' | 'en', goal: string) {
  const isPt = locale === 'pt-BR';
  return {
    'agent-planner': { action: isPt ? `Planejou etapas para: ${goal.slice(0, 60)}` : `Planned steps for: ${goal.slice(0, 60)}`, handoffTo: 'tutor-agent', tool: 'search_evidence', toolInput: { query: goal } },
    'agent-tutor': { action: isPt ? 'Explicou o conceito com base nas fontes.' : 'Explained the concept from sources.', handoffTo: 'question-gen' },
    'agent-question-gen': { action: isPt ? 'Gerou uma questão de múltipla escolha.' : 'Generated a multiple-choice question.', handoffTo: 'fact-checker', tool: 'compute_example', toolInput: { expr: '75*70' } },
    'agent-fact-checker': { action: isPt ? 'Verificou as citações nas fontes fornecidas.' : 'Checked citations against supplied sources.' },
    'agent-orchestrator': {
      locale,
      summary: isPt ? `Rascunho sobre "${goal.slice(0, 80)}" gerado por 4 agentes.` : `Draft about "${goal.slice(0, 80)}" generated by 4 agents.`,
      agentTrace: [
        { agentId: 'planner', role: 'planner', action: isPt ? 'Definiu etapas de estudo.' : 'Defined study steps.', handoffTo: 'tutor-agent' },
        { agentId: 'tutor-agent', role: 'tutor', action: isPt ? 'Explicou o conceito.' : 'Explained the concept.', handoffTo: 'question-gen' },
        { agentId: 'question-gen', role: 'question-generator', action: isPt ? 'Gerou questão.' : 'Generated question.', handoffTo: 'fact-checker' },
        { agentId: 'fact-checker', role: 'fact-checker', action: isPt ? 'Verificou fontes.' : 'Verified sources.' },
      ],
      draft: {
        title: isPt ? `Plano de estudo: ${goal.slice(0, 60)}` : `Study plan: ${goal.slice(0, 60)}`,
        body: isPt
          ? `Rascunho demonstrativo (fixture offline). Débito cardíaco = FC × VS. Exemplo: 75 × 70 mL = 5.250 mL/min = 5,25 L/min. Este conteúdo exige revisão médica humana antes de qualquer uso educacional público.`
          : `Demo draft (offline fixture). Cardiac output = HR × SV. Example: 75 × 70 mL = 5,250 mL/min = 5.25 L/min. This content requires human medical review before any public educational use.`,
        evidenceKeys: [sourceKey],
      },
      toolCalls: [
        { tool: 'search_evidence', agentId: 'planner' },
        { tool: 'compute_example', agentId: 'question-gen' },
      ],
    },
  };
}

// Server action que chama o orquestrador multi-agente.
// Sempre retorna draft (nunca publica). Sem AI_LIVE_ENABLED, usa fixture offline demonstrativa.
export async function runAgentOrchestrator(input: unknown): Promise<{ ok: true; draft: OrchestratorDraft } | { ok: false; error: string }> {
  try {
    const parsed = orchestratorRequestSchema.safeParse(input);
    if (!parsed.success) return { ok: false, error: 'INVALID_INPUT' };
    const records: AgentRunRecord[] = [];
    const isLive = process.env.AI_LIVE_ENABLED === 'true';
    const runtime = createAiRuntime({
      mode: isLive ? 'live' : 'fixture',
      response: { output: {} },
      agentResponses: isLive ? {} : defaultFixtureResponses(parsed.data.studyLocale, parsed.data.goal),
      onAgentRun: (r) => { records.push(r); },
    });
    const draft = await runtime.agents.run(parsed.data);
    return { ok: true, draft };
  } catch (error) {
    if (error instanceof AiRunError) return { ok: false, error: error.code };
    return { ok: false, error: 'PROVIDER_FAILED' };
  }
}
